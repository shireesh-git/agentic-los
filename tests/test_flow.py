def test_a_returned_proposal_asks_the_rm_to_rerun_and_each_officer_sees_only_their_prompts(svc):
    """User testing F5–F7: Underwriting changes the amount and returns the proposal; the RM (not Rahul) is asked
    whether to re-run the CAM; Yes re-runs it. Suggestions refresh once asked; fields entered by people are
    attributed by role; the progress view keeps analysis and section writing apart."""
    rm, cro = login(svc, "f_rm"), login(svc, "f_cro")
    svc.reset(rm, E)
    cid = _generated(svc, rm)["case_id"]
    job = svc.cam_progress(cid)["job"]
    assert [p["id"] for p in job["phases"]] == ["analysis", "writing"]
    assert all(i["status"] == "done" and i["ms"] is not None for i in job["phases"][0]["items"])
    assert {i["status"] for i in job["phases"][1]["items"]} <= {"done", "reused", "not_applicable"}

    v = svc.view(cid, rm)
    if v["ask"]:
        group = next(g for g in v["groups"] if any(p["id"] == v["ask"]["ref"] for p in g["points"]))
        assert group["missing"] >= 1                               # F2: the group knows how many are pending
    else:                                                          # every field is filled by the agents (demo data)
        svc.set_datapoint(cid, rm, "corporate_governance", "Board of 12, 7 independent directors", "")
        v = svc.view(cid, rm)
    first = v["suggestions"][0]
    svc.chat(cid, rm, first)
    v = svc.view(cid, rm)
    assert first not in v["suggestions"] and len(v["suggestions"]) == 2      # F5: replaced by the next question
    assert not [m for m in v["chat"] if "Still waiting" in m["text"]]
    while v["ask"] and v["ask"]["kind"] == "dp":
        svc.chat(cid, rm, "Multiple banking" if v["ask"]["ref"] == "banking_arrangement" else "Direct enterprise sales")
        v = svc.view(cid, rm)
    assert v["counts"]["by_role"] == [{"role": "rm", "label": "Relationship Manager", "short": "RM", "count": 1}]
    svc.act(cid, rm, "approve", "Submitted")

    svc.set_datapoint(cid, cro, "amount_cr", 600, "Client revised the requirement")
    v = svc.view(cid, cro)
    assert v["ask"]["kind"] == "rerun" and "You changed Amount requested" in v["ask"]["text"]
    svc.act(cid, cro, "send_back", "Client revised the amount to 600 Cr — please confirm the request")
    v = svc.view(cid, cro)
    assert v["ask"] is None                                         # F6: Rahul is not shown the RM's prompt
    assert "Returned to Ananya Rao" in [m for m in v["chat"] if m["stage"] == "credit_risk"][-1]["text"]
    v = svc.view(cid, rm)
    assert v["ask"]["kind"] == "rerun" and "Rahul Mehta (Underwriting) changed Amount requested from ₹500.00 Cr to " \
                                           "₹600.00 Cr" in v["ask"]["text"]
    assert not next(a for a in v["actions"] if a["id"] == "approve")["enabled"]   # CAM out of date blocks submit
    svc.chat(cid, rm, "Yes, re-run")
    case = svc.wait_for_cam(cid, timeout=300)
    assert case["cam"]["state"] == "ready" and not case["cam"]["stale"]
    assert svc.cases.get(E)["requested_amount_cr"] == 600
    v = svc.view(cid, rm)
    assert next(a for a in v["actions"] if a["id"] == "approve")["enabled"]
    svc.reset(rm, E)
