def test_the_cam_pdf_survives_ai_written_markup():
    """AI-written CAM text with a bare <br>, "<" or "&" broke the PDF download (a 500 after a re-run)."""
    import fitz

    from src.rendering.cam_pdf import generate_cam_pdf

    md = ("## 1. Summary\n### Profile <A&B>\nLine one<br>line two & D/E < 2.5x, **bold** and *italic*\n"
          "- bullet <br> with **x**\n| a | b<br>c |\n|---|---|\n| 1 < 2 | x & y |\n| r | <br> |\n*Source: A & B*")
    pdf = generate_cam_pdf(md, "Johnson & Johnson <Pvt>")
    text = " ".join(p.get_text() for p in fitz.open(stream=pdf, filetype="pdf"))
    assert pdf.startswith(b"%PDF") and "D/E < 2.5x" in text and "x & y" in text and "JOHNSON & JOHNSON" in text


def test_a_plain_text_ai_answer_is_used_and_still_checked():
    """With a long record the model may answer in plain text instead of JSON: use it, but still reject
    figures that are not in the record."""
    from src.flow import copilot as cp

    class Plain:
        name = "nim"

        def __init__(self, reply):
            self.reply = reply

        def generate(self, **_):
            return self.reply

    rec = {"purpose": "New 500-bed hospital in Pune", "amount_cr": 750}
    ok = cp.ask("What is the purpose?", rec, Plain("A new 500-bed hospital in Pune."))
    assert ok["mode"] == "ai" and "Pune" in ok["answer"]
    bad = cp.ask("How much?", rec, Plain("The loan is 9,999 crore."))
    assert bad["mode"] == "lookup"


