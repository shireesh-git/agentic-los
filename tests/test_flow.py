"""The agentic LOS (src/flow), end to end for Infosys: RM → Credit Risk → Sanctioning Authority → CAD →
Disbursement Authoriser, with the CAM generated by the CAM engine (template narrative under the mock
provider), the chat filling gaps, a Credit Risk change the SA must accept, documents checked by the agent,
and the reports. Then a reset and the same journey from the downloaded CAM, uploaded."""

import json

import pytest

from src.application.container import build_container
from src.flow import datapoints as dpx

E = "INFY001"


@pytest.fixture(scope="module")
def svc():
    """The flow service; the CAM engine runs these tests make for Infosys are removed afterwards, so later
    tests see the shared test database as it was (some assume Infosys has no CAM)."""
    from src.services.persistence import persistence

    def runs():
        with persistence._connect() as conn:
            return ({r[0] for r in conn.execute("SELECT run_id FROM case_runs WHERE entity_id = ?", (E,))},
                    {r[0] for r in conn.execute("SELECT run_id FROM pipeline_runs WHERE entity_id = ?", (E,))})

    cases_before, attempts_before = runs()
    flow = build_container().flow
    flow.reset({"user": {"id": "test"}}, E)
    yield flow
    flow.reset({"user": {"id": "test"}}, E)
    cases_after, attempts_after = runs()
    with persistence._connect() as conn:
        conn.executemany("DELETE FROM case_runs WHERE run_id = ?", [(r,) for r in cases_after - cases_before])
        conn.executemany("DELETE FROM pipeline_runs WHERE run_id = ?", [(r,) for r in attempts_after - attempts_before])


def login(svc, uid):
    return svc.sign_in(uid)


def _generated(svc, rm):
    case = svc.create(rm, entity_id=E)
    svc.generate_cam(case["case_id"], rm)
    case = svc.wait_for_cam(case["case_id"], timeout=300)
    assert case["cam"]["state"] == "ready", case["cam"]
    return case


def test_infosys_end_to_end(svc):
    rm, cro, sa, cad, da = (login(svc, u) for u in ("f_rm", "f_cro", "f_sa", "f_cad", "f_da"))
    case = _generated(svc, rm)
    cid = case["case_id"]
    v = svc.view(cid, rm)
    assert v["counts"]["filled"] >= 28 and v["cam"]["mode"] == "generate"
    rev = next(p for g in v["groups"] for p in g["points"] if p["id"] == "revenue_cr")
    assert rev["value"] == pytest.approx(153670.0) and rev["source"]["kind"] == "engine" and rev["source"]["section"]
    assert v["progress"] is None and svc.cam_progress(cid)["job"]["percent"] == 100

    # the mandatory checks ran at initiation from the demo bureau / MCA / registry file (E5), all clear
    assert v["checks"]["total"] >= 6 and v["checks"]["clear"] == v["checks"]["total"] and v["checks"]["demo"]
    assert v["verdict"]["tone"] == "good" and "mandatory checks are clear" in v["verdict"]["text"]
    # the lender count in the (demo) bureau report fills the banking arrangement, so nothing is left to ask;
    # agent-only fields (outlook, marketing, metrics) are never asked
    pts = {p["id"]: p for g in v["groups"] for p in g["points"]}
    assert pts["banking_arrangement"]["value"].startswith("Multiple banking") and not v["ask"]
    # a question for a closed-answer field offers its answers, the record's suggestion first, skip last (E1)
    q = svc._dp_question(svc.store.get(cid), dpx.spec("banking_arrangement"))
    assert q["quick"][0] == q["suggested"] == "Multiple banking" and set(q["quick"]) == {"Sole banking", "Multiple banking",
                                                                                         "Consortium"}
    assert q["secondary"] == ["Not provided"] and "lender" in q["text"] and q["hint"]
    svc.skip_datapoint(cid, rm, "corporate_governance")
    v = svc.view(cid, rm)
    skipped = [p["id"] for g in v["groups"] for p in g["points"] if p["status"] == "skipped"]
    assert skipped == ["corporate_governance"]
    inc = {f["id"]: f for f in v["incomplete"]}                                          # E7: which, and who
    assert inc["corporate_governance"]["status"] == "not_provided" and "Ananya" in inc["corporate_governance"]["note"]

    # the downloaded CAM carries its data sheet
    pdf, name = svc.cam_file(cid, rm)
    assert name.endswith(".pdf") and dpx.read_sheet(pdf)["datapoints"]["revenue_cr"]["value"] == pytest.approx(153670.0)

    with pytest.raises(Exception):
        svc.act(cid, cro, "approve")                         # not Credit Risk's turn yet
    svc.act(cid, rm, "approve", "Ready for review")
    v = svc.view(cid, cro)
    assert v["stage"] == "credit_risk" and v["is_mine"] and v["ask"]["ref"] == skipped[0]   # the RM's skip, raised

    svc.chat(cid, cro, "Leave as not provided")
    svc.chat(cid, cro, "change EBITDA to 35900 because one-off gain excluded")
    v = svc.view(cid, cro)
    ch = v["changes"][0]
    assert (ch["dp"], ch["old"], ch["new"], ch["reason"], ch["status"]) == \
           ("ebitda_cr", pytest.approx(39594.5), 35900.0, "one-off gain excluded", "pending")
    assert v["cam"]["stale"] and not next(a for a in v["actions"] if a["id"] == "approve")["enabled"]

    # the re-run assesses the changed figure; the person's value is kept
    svc.generate_cam(cid, cro)
    svc.wait_for_cam(cid, timeout=300)
    v = svc.view(cid, cro)
    eb = next(p for g in v["groups"] for p in g["points"] if p["id"] == "ebitda_cr")
    assert not v["cam"]["stale"] and eb["value"] == 35900.0 and eb["source"]["kind"] == "person"
    assert svc.cases.get(E)["fact_pack"]["financial_summary"]["periods"]["FY2025"]["ebitda_cr"] == pytest.approx(35900.0)
    svc.act(cid, cro, "approve", "Recommend")

    # the SA must concur with each override before Sanction is enabled; Rahul is not asked the SA's question
    v = svc.view(cid, cro)
    assert v["ask"] is None and "Submitted to Vikram Shah" in [m for m in v["chat"] if m["stage"] == "credit_risk"][-1]["text"]
    v = svc.view(cid, sa)
    assert v["ask"]["kind"] == "change" and "Underwriting override by Rahul Mehta: FY2025 EBITDA" in v["ask"]["text"]
    assert not next(a for a in v["actions"] if a["id"] == "approve")["enabled"]
    svc.chat(cid, sa, "Return with remarks")
    svc.chat(cid, sa, "Show the one-off gain in the notes")
    v = svc.view(cid, sa)
    assert v["changes"][0]["status"] == "disputed"
    svc.act(cid, sa, "send_back", "Evidence for the one-off gain, please")
    v = svc.view(cid, cro)
    assert v["stage"] == "credit_risk" and "Evidence for the one-off gain" in " ".join(m["text"] for m in v["chat"][-3:])
    svc.act(cid, cro, "approve", "Note 27 of the annual report shows the one-off gain")
    v = svc.view(cid, sa)
    assert v["changes"][0]["status"] == "pending"
    svc.chat(cid, sa, "Concur")
    v = svc.view(cid, sa)
    assert next(a for a in v["actions"] if a["id"] == "approve")["enabled"]
    svc.act(cid, sa, "approve", "Sanctioned")

    # CAD: risk-based conditions — for an FD lien of ₹500 Cr: insurance not applicable, KYC met from the record,
    # legal vetting required (≥ ₹100 Cr), charge registration a condition subsequent
    v = svc.view(cid, cad)
    cond = {c["id"]: c for c in v["conditions"]}
    assert v["sanction"]["limit_cr"] == pytest.approx(500.0)
    assert cond["insurance"]["status"] == "not_applicable" and cond["kyc_refresh"]["status"] == "auto"
    assert cond["legal_vetting"]["status"] == "open" and cond["charge_filing"]["when"] == "subsequent"
    assert "Sanction of working capital facility" in svc.sanction_letter(cid)
    assert v["ask"]["kind"] == "cond_doc" and v["ask"]["quick"] == ["Add demo signed documents"]
    # E8: the upload prompt says where — upload in the chat, or go to the condition's row
    assert v["ask"]["upload"]["condition"] == v["ask"]["ref"] and v["ask"]["goto"]["target"] == "sec-cp"
    assert "Conditions Precedent" in v["ask"]["text"]
    svc.chat(cid, cad, "Add demo signed documents")                    # Copilot guides CAD through the CPs
    v = svc.view(cid, cad)
    added = next(m for m in reversed(v["chat"]) if m.get("docs"))
    assert added["goto"]["target"] == "sec-cp" and "Conditions Precedent" in added["text"]
    assert all(d["name"].endswith(".pdf") and d["demo"] and d["label"] in added["text"] for d in added["docs"])
    assert all(c["status"] in ("verified", "auto") for c in v["conditions"] if c["when"] == "precedent"
               and c["status"] != "not_applicable")
    assert v["ask"]["kind"] == "submit_release"
    with pytest.raises(Exception):
        svc.set_drawdown(cid, cad, amount_cr=600)
    svc.set_drawdown(cid, cad, amount_cr=450)
    v = svc.view(cid, cad)
    assert v["ask"]["kind"] == "submit_release" and "₹450.00 Cr" in v["ask"]["text"]
    svc.chat(cid, cad, "Yes, submit")
    # E9: the request names who submitted and edited it; nothing empty reaches the Copilot
    from src.flow import copilot as cp
    dd = svc._drawdown_record(svc.store.get(cid))
    assert dd["submitted"].startswith("by Meera Iyer") and "Meera Iyer" in dd["edited"]
    rec = json.dumps(cp.clean(svc._record(svc.store.get(cid))), ensure_ascii=False)
    assert "null" not in rec and "None" not in rec and "HR_" not in rec and "₹450 Cr" in rec
    v = svc.view(cid, da)
    assert v["stage"] == "disbursement" and all(c["ok"] for c in v["release_checks"])
    svc.act(cid, da, "approve", "Released")
    v = svc.view(cid, da)
    assert v["status"] == "disbursed" and v["release"]["amount_cr"] == 450 and all(
        s["state"] == "done" for s in v["chain"])
    cs = next(c for c in v["conditions"] if c["id"] == "charge_filing")
    assert cs["due"] and cs["status"] == "open"

    pack = svc.audit_pack(cid, da)
    for text in ("Agents proposed; named people decided", "FY2025", "Vikram Shah", "accepted",
                 "not applicable", "Subsequent", "Released"):
        assert text in pack, text
    rep = svc.time_report()
    row = next(r for r in rep["cases"] if r["case_id"] == cid)
    assert row["touches"] >= 10 and row["datapoints"]["auto_pct"] > 80 and rep["baseline"]["total_hours"] > 0
    an = rep["analytics"]
    assert an["funnel"][-1]["count"] >= 1 and an["cam"]["runs"] >= 1 and an["bottleneck"]
    assert an["filled"]["agent"] > 0 and len(an["activity"]) == 14 and an["activity"][-1]["events"] > 0
    assert any(i["title"] == "Effort" for i in an["insights"]) and an["outcomes"]["disbursed"] >= 1
    assert an["outcomes"]["time_to_sanction"] and next(r for r in rep["cases"] if r["case_id"] == cid)["outcome"] == "Disbursed"

    # reset, then the same borrower from the downloaded CAM
    svc.reset(rm, E)
    assert not [c for c in svc.store.all() if c["entity_id"] == E]
    case = svc.create(rm, entity_id=E)
    svc.upload_cam(case["case_id"], rm, name, pdf)
    v = svc.view(case["case_id"], rm)
    assert v["cam"]["mode"] == "upload" and v["cam"]["read_by"] == "sheet"
    rev = next(p for g in v["groups"] for p in g["points"] if p["id"] == "revenue_cr")
    assert rev["value"] == pytest.approx(153670.0) and rev["source"]["kind"] == "upload"
    assert v["counts"]["filled"] >= 29


