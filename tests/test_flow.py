def test_the_flow_page_script_parses():
    """A syntax error in flow.js blanks the whole page (an unescaped apostrophe did it to los.js once)."""
    import shutil
    import subprocess
    from pathlib import Path
    node = shutil.which("node")
    if not node:
        pytest.skip("Node.js is not installed")
    script = Path(__file__).resolve().parents[1] / "src" / "ui" / "static" / "js" / "flow" / "flow.js"
    r = subprocess.run([node, "-e", "new Function(require('fs').readFileSync(process.argv[1], 'utf8'))", str(script)],
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stderr[-800:]


