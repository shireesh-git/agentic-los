    assert pts["internal_rating"]["value"] == "AA-" and pts["internal_rating"]["source"]["page"] == 1
    assert pts["company_name"]["source"]["kind"] == "record" and pts["amount_cr"]["value"] == 500.0
    assert v["counts"]["missing"] > 0 and v["ask"]["kind"] == "dp"
    svc.reset(rm, E)


