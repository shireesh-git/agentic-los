def prose(text: str, limit: int = 1200) -> str:
    """Paragraph text of a section (tables and sub-headings dropped), trimmed at a sentence."""
    lines = [ln.strip() for ln in (text or "").splitlines()]
    body = " ".join(ln for ln in lines if ln and not ln.startswith(("|", "#", "---"))
                    and not re.match(r"^\*?(?:sources?|note)\s*:", ln, re.I))
    body = re.sub(r"\*\*(.+?)\*\*", r"\1", body)
    body = re.sub(r"(?<!\w)\*(.+?)\*(?!\w)", r"\1", body)
    body = re.sub(r"\s+", " ", body).strip()
    if len(body) <= limit:
        return body
    cut = body[:limit]
    return cut[:cut.rfind(". ") + 1] if ". " in cut else cut + "…"


def _inline(v) -> str:
    if isinstance(v, dict):
        return "; ".join(f"{k}: {x}" for k, x in v.items() if x not in (None, "", [], {}))
    if isinstance(v, list):
        return "; ".join(_inline(x) if isinstance(x, (dict, list)) else str(x) for x in v[:8])
    return str(v)


def risks_text(challenges: list, responses: dict, observations: list) -> str:
    """One structured list of risks, each with its mitigant: the challenge agent's challenges (answered or
    open), then the engine's high / medium observations not already covered."""
    lines = []
    for c in challenges:
        cid = c.get("challenge_id") or c.get("id")
        r = (responses or {}).get(cid)
        asks = c.get("required_response") or c.get("asks") or []
        ask = asks[0] if isinstance(asks, list) and asks else (asks if isinstance(asks, str) else "")
        how = ({"justify": "justified", "override": "figure overridden", "send_back": "returned for documents",
                "reject": "declined"}.get(r["kind"], r["kind"]) + (f" — {r['note']}" if r.get("note") else "")
               ) if r else (f"open; sought: {ask}" if ask else "open")
        lines.append(f"{c.get('title')} ({str(c.get('severity') or '').lower()}) — mitigant: {how}")
    seen = {str(c.get("title") or "").lower() for c in challenges}
    for o in observations:
        if str(o.get("severity")).upper() in ("HIGH", "MEDIUM") and str(o.get("title") or "").lower() not in seen:
            lines.append(f"{o.get('title')} ({str(o.get('severity')).lower()}) — {o.get('summary') or ''}".rstrip(" —"))
    return _bullets(lines)


def _bullets(items) -> str:
    return "\n".join(f"• {str(x).strip()}" for x in items if str(x or "").strip())


