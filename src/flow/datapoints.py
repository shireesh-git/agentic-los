def from_reading(reading: dict, file_name: str) -> dict[str, dict]:
    """Data points from the CAM intake agent's reading of an uploaded CAM, with page evidence."""
    out: dict[str, dict] = {}
    for key, dp_id in _FROM_SECTIONS.items():
        s = (reading.get("sections") or {}).get(key)
        if s and s.get("text"):
            if dp_id in out:                                     # two sections feed one point: keep both
                out[dp_id]["value"] = (out[dp_id]["value"] + "\n" + s["text"])[:3000]
                continue
            out[dp_id] = {"value": s["text"][:3000], "source": {
                "kind": "upload", "label": f"Uploaded CAM · page {s['page']}", "page": s["page"],
                "section": s.get("heading"), "document": file_name, "excerpt": s["text"][:1800]}}
    for key, dp_id in _FROM_LABELS.items():
        hit = (reading.get("labels") or {}).get(key)
        if hit and hit.get("value") not in (None, ""):
            sp = spec(dp_id) or {}
            value = hit["value"]
            if numeric(sp):
                try:
                    value = parse_value(sp, value)
                except ValueError:
                    continue
            out[dp_id] = {"value": value, "source": {
                "kind": "upload", "label": f"Uploaded CAM · page {hit['page']}", "page": hit["page"],
                "document": file_name, "excerpt": hit.get("snippet") or "",
                "confidence": confidence(70, f"Read from the bank's CAM (page {hit['page']}); not recomputed")
                if numeric(sp) else None}}
    return out


def read_sheet(pdf_bytes: bytes) -> Optional[dict]:
    """The data sheet embedded in a CAM this platform generated, or None."""
    import fitz

    try:
        with fitz.open(stream=pdf_bytes, filetype="pdf") as doc:
            if SHEET_NAME not in doc.embfile_names():
                return None
            sheet = json.loads(doc.embfile_get(SHEET_NAME).decode("utf-8"))
    except Exception:
        return None
    return sheet if sheet.get("format") == SHEET_FORMAT else None


def embed_sheet(pdf_bytes: bytes, sheet: dict) -> bytes:
    import fitz

    with fitz.open(stream=pdf_bytes, filetype="pdf") as doc:
        doc.embfile_add(SHEET_NAME, json.dumps(sheet, ensure_ascii=False, default=str).encode("utf-8"),
                        filename=SHEET_NAME, desc="Data points of this CAM (agentic LOS)")
        return doc.tobytes(garbage=1, deflate=True)


def page_texts(pdf_bytes: bytes, limit: int = 60) -> list[str]:
    import fitz

    with fitz.open(stream=pdf_bytes, filetype="pdf") as doc:
        return [doc[i].get_text() for i in range(min(doc.page_count, limit))]


def find_page(pages: list[str], sp: dict, value) -> Optional[int]:
    """The first page an uploaded CAM shows a value on (evidence for a data point read from its sheet)."""
    if value in (None, ""):
        return None
    if numeric(sp) and isinstance(value, (int, float)):
        needles = [f"{value:,.2f}", f"{value:,.0f}", f"{value:.2f}", str(value)]
    else:
        first = re.sub(r"^[•\s]+", "", str(value)).split("\n")[0]
        needles = [first[:40]]
    for pno, text in enumerate(pages, start=1):
        flat = re.sub(r"\s+", " ", text)
        if any(n and n in flat for n in needles):
            return pno
    return None
