_CIN = re.compile(r"^([LU])(\d{5})([A-Z]{2})(\d{4})([A-Z]{3})(\d{6})$")
_CIN_TYPES = {"PLC": "Public limited company", "PTC": "Private limited company", "GOI": "Government company",
              "SGC": "State government company", "FLC": "Public limited company (subsidiary of a foreign company)",
              "FTC": "Private limited company (subsidiary of a foreign company)", "NPL": "Section 8 (not-for-profit) company",
              "GAP": "Company limited by guarantee", "OPC": "One person company", "ULL": "Unlimited liability company"}


def constitution_from_cin(cin: Optional[str]) -> Optional[str]:
    """The constitution a CIN encodes: L/U (listed / unlisted) and the company class, e.g. PLC, PTC."""
    c = str(cin or "").strip().upper()
    if re.match(r"^[A-Z]{3}-\d{4}$", c):
        return "Limited liability partnership (LLPIN)"
    m = _CIN.match(c)
    if not m or m.group(5) not in _CIN_TYPES:
        return None
    return (f"{_CIN_TYPES[m.group(5)]} ({'listed' if m.group(1) == 'L' else 'unlisted'}), "
            f"incorporated {m.group(4)}")


def _latest_period(fp: dict) -> tuple[Optional[str], dict]:
    periods = ((fp.get("financial_summary") or {}).get("periods") or {})
    if not periods:
        return None, {}
    key = max(periods)
    return key, periods[key] or {}


def from_engine(case: dict) -> dict[str, dict]:
    """Data points from a CAM engine case: {id: {"value", "source"}}; absent → a gap."""
    fp = case.get("fact_pack") or {}
    md = case.get("cam_text") or ""
    bp = fp.get("borrower_profile") or {}
    cs = fp.get("case_summary") or {}
    fd = fp.get("facility_details") or {}
    out: dict[str, dict] = {}

    prov = fp.get("data_provenance") or {}
    period, figs = _latest_period(fp)
    fin_src = str(figs.get("data_source") or "")
    fin_demo = (prov.get("financial_summary") or {}).get("class") == "synthetic_demo"
    fin_conf = 40 if fin_demo else 90 if "audited" in fin_src.lower() else 70 if "provisional" in fin_src.lower() else 75
    fin_basis = ("Demo financials, not verified" if fin_demo else f"{period} {fin_src or 'financial statements'}")
    truth = fp.get("revenue_truth") or {}

    def conf_for(dp_id: str) -> Optional[dict]:
        sp = spec(dp_id) or {}
        if not numeric(sp) and dp_id not in ("internal_rating", "external_rating", "crilc_sma"):
            return None
        if dp_id == "revenue_cr":
            st = truth.get("status")
            adj, note = {"good": (10, "agrees with GST / bank data"), "warn": (-10, "differs from GST / bank data"),
                         "bad": (-35, "not supported by GST / bank data")}.get(st, (-5, "not cross-checked against GST or bank data"))
            return confidence(fin_conf + adj, f"{fin_basis}; {note}")
        if dp_id in ("ebitda_cr", "pat_cr", "net_worth_cr", "total_debt_cr"):
            return confidence(fin_conf, fin_basis)
        if sp.get("group") == "metrics" and sp.get("computed"):
            return confidence(fin_conf - 5, f"Calculated from {fin_basis}")
        if dp_id in ("bureau_score", "crilc_sma"):
            cls = (prov.get("external_intelligence") or {}).get("class")
            return confidence(40 if cls == "synthetic_demo" else 90, "Demo bureau data" if cls == "synthetic_demo"
                              else "Bureau / CRILC record")
        if dp_id == "collateral_fsv_cr":
            return confidence(65, "Valuation as submitted; independent valuation not on record")
        if dp_id == "internal_rating":
            return confidence(fin_conf - 5, "Rating model on the statements on record")
        if dp_id == "external_rating":
            return confidence(85, "Borrower record (rating agency)")
        if dp_id in ("amount_cr", "tenor_months", "recommended_cr"):
            return confidence(95, "Facility request on the proposal")
        return confidence(75, "CAM engine")

    def put(dp_id, value, section: str = "", detail: str = ""):
        if value in (None, "", [], "N/A"):
            return
        heading, text = md_section(md, SECTIONS[section]) if section else ("", "")
        out[dp_id] = {"value": value, "source": {
            "kind": "engine", "label": "CAM engine" + (f" · §{heading}" if heading else ""),
            "section": heading or None, "detail": detail, "run_id": case.get("run_id"), "excerpt": text[:1800],
            "confidence": conf_for(dp_id)}}

    def text_of(section: str, limit: int = 1200) -> str:
        return prose(md_section(md, SECTIONS[section])[1], limit)

    put("company_name", bp.get("company_name") or case.get("company_name"), "identity", "Borrower record (MCA master)")
    put("cin", bp.get("cin"), "identity", "Borrower record (MCA master)")
    put("pan", bp.get("pan"), "identity", "Borrower record")
    sector = (cs.get("sector") or case.get("sector") or "").replace("_", " ").capitalize()
    put("sector", re.sub(r"^It\b", "IT", sector) or None, "identity")
    put("subsector", cs.get("subsector"), "identity")
    derived = constitution_from_cin(bp.get("cin"))
    if derived:
        put("constitution", derived + (f"; listed on {bp['listed_exchange']}" if bp.get("listed_exchange")
                                       and "(listed)" in derived else ""), "identity", "Derived from the CIN")
    elif (cs.get("borrower_type") or "") == "listed":
        ex = bp.get("listed_exchange")
        put("constitution", "Public limited company (listed" + (f" on {ex})" if ex else ")"), "identity",
            "Borrower record")
    # Banking arrangement only from a lender count on record (bureau / CRILC) — never read from the
    # AI-written text, which guesses ("no consortium participation" mentions "consortium").
    ei = fp.get("external_intelligence") or {}
    lenders = ei.get("bureau_total_lenders") or ((fp.get("crilc_exposure") or {}).get("aggregate_summary") or {}).get("lender_count")
    if isinstance(lenders, (int, float)) and lenders >= 1:
        put("banking_arrangement", "Sole banking" if int(lenders) == 1 else f"Multiple banking ({int(lenders)} lenders)",
            "", "Lender count from the bureau / CRILC record")
    put("business_background", text_of("business"), "business")
    put("corporate_governance", text_of("governance"), "governance")

    ftype = fd.get("facility_type") or case.get("facility_type")
    put("product", str(ftype).replace("_", " ").capitalize() if ftype else None, "facility", "Facility request")
    put("amount_cr", case.get("requested_amount_cr") or fd.get("amount_requested_cr"), "facility", "Facility request")
    put("tenor_months", fd.get("tenor_months"), "facility", "Facility request")
    put("purpose", fd.get("purpose") or cs.get("purpose"), "facility", "Facility request")
    rec = ((case.get("reassessment") or {}).get("facility_recommendation") or {})
    put("recommended_cr", rec.get("recommended_cr") or fd.get("proposed_limit_cr"), "facility",
        rec.get("structure") or "Facility assessment")
    pricing = fp.get("facility_pricing") or {}
    put("pricing", pricing.get("interest_rate"), "pricing", pricing.get("basis") or "")

    src = f"{period} · {figs.get('data_source') or 'financial statements'}" if period else ""
    for dp_id, section in (("revenue_cr", "pnl"), ("ebitda_cr", "pnl"), ("pat_cr", "pnl"),
                           ("net_worth_cr", "balance_sheet"), ("total_debt_cr", "balance_sheet")):
        if isinstance(figs.get(dp_id), (int, float)):
            put(dp_id, round(float(figs[dp_id]), 2), section, src)

    if case.get("risk_grade") and case["risk_grade"] != "N/A":
        put("internal_rating", f"{case['risk_grade']} (score {float(case.get('composite_score') or 0):.1f}/100)",
            "internal_rating", "Internal rating scorecard")
    put("external_rating", bp.get("credit_rating"), "external_rating", bp.get("rating_agency") or "")
    put("strengths", _bullets(s.get("detail") for s in fp.get("credit_strengths") or []), "swot")
    put("risks_mitigants", risks_text(case.get("challenges") or [], {}, case.get("observations") or []), "",
        "Credit Challenge Agent and credit observations (engine)")
    ia = fp.get("industry_analysis") or {}
    put("industry_outlook", ia.get("industry_overview") or text_of("industry"), "industry")
    mkt = [f"Revenue segments: {_inline(ia.get('revenue_segments'))}" if ia.get("revenue_segments") else "",
           f"Geographic mix: {_inline(ia.get('geographic_mix'))}" if ia.get("geographic_mix") else "",
           f"Clients: {_inline((fp.get('sector_kpis') or {}).get('client_metrics'))}"
           if (fp.get("sector_kpis") or {}).get("client_metrics") else ""]
    put("marketing_arrangements", "\n".join(x for x in mkt if x), "", "Industry analysis and sector KPIs (engine)")

    # credit metrics: the latest year's ratios against policy, and the quality checks
    ra = fp.get("ratio_analysis") or {}
    latest = ra.get(max(ra)) if ra else {}
    rsrc = f"Ratio engine · {max(ra)}" if ra else ""
    for dp_id, key in (("dscr", "dscr"), ("interest_cover", "interest_coverage_ratio"),
                       ("debt_to_ebitda", "debt_to_ebitda"), ("current_ratio", "current_ratio"),
                       ("tol_tnw", "tol_tnw"), ("debt_to_equity", "debt_to_equity")):
        v = (latest.get(key) or {}).get("value")
        if isinstance(v, (int, float)):
            put(dp_id, round(float(v), 2), "", f"{rsrc} · {(latest.get(key) or {}).get('formula') or ''}".strip(" ·"))
    dc = fp.get("debt_capacity") or {}
    if dc.get("available"):
        put("sustainable_limit_cr", dc.get("sustainable_cr"), "",
            f"Bound by {dc.get('binding') or '—'}. {(dc.get('recommendation') or {}).get('text') or ''}".strip())
    eq = fp.get("earnings_quality") or {}
    if eq.get("available"):
        put("earnings_quality", eq.get("score"), "", "; ".join(f"{m['label']} {m['display']}" for m in eq.get("metrics") or []))
    if truth.get("score") is not None:
        put("revenue_truth", truth["score"], "", truth.get("summary") or "")
    ews = fp.get("ews_indicators") or {}
    if ews.get("available"):
        put("ews_flags", ews.get("flags"), "", f"{ews.get('flags')} flag(s) of {ews.get('checked')} indicator(s) checked; "
            f"{ews.get('not_checked')} not checkable from the data on record")
    ecl = fp.get("ecl") or {}
    if ecl.get("available"):
        put("ecl_cr", ecl.get("ecl_cr"), "", ecl.get("basis", "") + (" Demo PD / LGD values." if ecl.get("demo") else ""))
        put("ecl_stage", ecl.get("stage"), "", ecl.get("stage_reason", ""))
    rules = (fp.get("policy_decisions") or {}).get("tier1_hard_rules") or []
    if rules:
        failed = [r.get("rule") for r in rules if r.get("result") == "fail"]
        put("hard_rules_failed", len(failed), "hard_rules",
            (", ".join(failed) + "; " if failed else "") + f"{sum(1 for r in rules if r.get('result') == 'not_verified')}"
            f" of {len(rules)} not verifiable from the data on record")
    put("bureau_score", ei.get("bureau_score"), "", "Bureau record")
    put("crilc_sma", ei.get("crilc_sma_flag"), "", "CRILC record")
    col = fp.get("collateral_analysis") or {}
    if col.get("collaterals"):
        put("collateral_fsv_cr", col.get("total_forced_sale_value_cr"), "security", "Collateral analysis (FSV)")
        if isinstance(col.get("coverage_ratio_fsv"), (int, float)):
            put("security_cover", round(float(col["coverage_ratio_fsv"]), 2), "security", "FSV ÷ facility amount")

    if col.get("collaterals"):
        lines = [f"{c.get('type')}: {c.get('description')} — market value ₹{float(c.get('market_value_cr') or 0):,.2f} Cr"
                 for c in col["collaterals"]]
        cover = col.get("coverage_ratio_market")
        if cover is not None:
            lines.append(f"Cover: {float(cover):.2f}x of the ₹{float(col.get('facility_amount_cr') or 0):,.2f} Cr facility")
        put("security", _bullets(lines), "security")
    put("key_terms", _bullets(case.get("conditions") or []), "conditions")
    put("covenants", _bullets(case.get("covenants_proposed") or []), "covenants")
    devs = [f"{e.get('description')}" for e in fp.get("validation_exceptions") or [] if e.get("status") != "resolved"]
    devs += [f"Not verified: {r.get('description')}" for r in (fp.get("policy_decisions") or {}).get("tier1_hard_rules") or []
             if r.get("result") in ("not_verified", "fail")]
    put("deviations", _bullets(devs) or "None", "hard_rules")
    if case.get("recommendation") and case["recommendation"] != "error":
        label = {"approve": "Approve", "refer": "Refer to the sanctioning authority",
                 "decline": "Decline"}.get(case["recommendation"], str(case["recommendation"]).title())
        put("recommendation", f"{label}. {case.get('rationale') or ''}".strip(), "recommendation")
    return out


