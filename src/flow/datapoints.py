# ── values ───────────────────────────────────────────────────────────────────

_NUM = re.compile(r"-?\d[\d,]*(?:\.\d+)?")


def parse_value(sp: dict, text) -> object:
    """A typed answer as the data point's type; raises ValueError when it is not one."""
    if sp.get("type") in ("amount", "number", "ratio", "score"):
        if isinstance(text, (int, float)):
            value = float(text)
        else:
            m = _NUM.search(str(text or "").replace("₹", ""))
            if not m:
                raise ValueError(f"{sp['label']} needs a number")
            value = float(m.group(0).replace(",", ""))
        return int(value) if sp["type"] in ("number", "score") else round(value, 2)
    value = str(text or "").strip()
    if not value:
        raise ValueError(f"{sp['label']} is empty")
    return value


def display(sp: dict, value) -> str:
    if value in (None, ""):
        return "—"
    if sp.get("type") == "amount" and isinstance(value, (int, float)):
        from src.flow.copilot import crore
        return crore(value)
    if sp.get("type") == "ratio" and isinstance(value, (int, float)):
        return f"{value:.2f}x"
    if sp.get("type") == "score" and isinstance(value, (int, float)):
        return f"{value:.0f} / 100"
    return str(value)


def numeric(sp: dict) -> bool:
    return sp.get("type") in ("amount", "number", "ratio", "score")


def band(sp: dict, value, thresholds: dict, values: dict) -> Optional[dict]:
    """How a value sits against its limit: {"status": good | warn | bad, "limit"}; None when unjudged.
    ``thresholds``: the engine's policy limits; ``values``: other data point values (for ``vs``)."""
    b = sp.get("band")
    if not b or not isinstance(value, (int, float)):
        return None
    if b.get("vs"):
        other = values.get(b["vs"])
        if not isinstance(other, (int, float)):
            return None
        return {"status": "good" if value >= other - 0.005 else "bad",
                "limit": f"recommended {display({'type': 'amount'}, other)}"}
    way = b.get("way") or ("max" if "max" in b else "min")
    lim = thresholds.get(b["policy"]) if b.get("policy") else b.get(way)
    if lim is None:
        return None
    lim = float(lim)
    shown = display({"type": sp.get("type")}, lim) if sp.get("type") != "number" else f"{lim:g}"
    if "warn_below" in b:                                    # scores: good ≥ min, amber ≥ warn_below, red below
        st = "good" if value >= lim else "warn" if value >= b["warn_below"] else "bad"
        return {"status": st, "limit": f"good ≥ {lim:g}"}
    if "bad_above" in b:                                     # counts: 0 good, 1 amber, more red
        st = "good" if value <= lim else "warn" if value <= b["bad_above"] else "bad"
        return {"status": st, "limit": f"max {lim:g}"}
    if way == "min":
        st = "bad" if value < lim else "warn" if value < lim * 1.10 else "good"
    else:
        st = "bad" if value > lim or value < 0 else "warn" if value > lim * 0.90 and lim > 0 else "good"
    return {"status": st, "limit": f"{way} {shown}"}


# ── confidence: how sure we are of a figure ─────────────────────────────────

def confidence(score: float, basis: str) -> dict:
    score = max(0, min(100, int(round(score))))
    return {"score": score, "level": "high" if score >= 80 else "medium" if score >= 60 else "low", "basis": basis}


def person_confidence(flagged: bool = False) -> dict:
    return confidence(30 if flagged else 50, "Entered by an officer; not independently verified"
                      + ("; differs from the audited statements" if flagged else ""))


def same(sp: dict, a, b) -> bool:
    if numeric(sp):
        try:
            return abs(float(a) - float(b)) < 0.005
        except (TypeError, ValueError):
            return False
    return str(a or "").strip() == str(b or "").strip()


# ── the CAM text ─────────────────────────────────────────────────────────────

def md_section(md: str, patterns) -> tuple[str, str]:
    """The CAM section whose heading matches the first of ``patterns`` that any heading matches (regexes on
    the title, numbering ignored) → (its heading, its text up to the next heading of the same or a higher
    level). Titles, not numbers: the AI-written and the template CAM number their sections differently."""
    heads = list(re.finditer(r"^(#{2,4})\s+((?:\d+(?:\.\d+)*\.?\s+)?)(.+)$", md or "", re.M))
    for pattern in ([patterns] if isinstance(patterns, str) else patterns):
        for m in heads:
            if not re.search(pattern, m.group(3), re.I):
                continue
            level = len(m.group(1))
            rest = md[m.end():]
            end = re.search(rf"^#{{1,{level}}}\s", rest, re.M)
            return (f"{m.group(2).strip()} {m.group(3).strip()}".strip(),
                    rest[:end.start() if end else len(rest)].strip())
    return "", ""


